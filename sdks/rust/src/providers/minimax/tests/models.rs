#[test]
fn explicit_adjustments_replacements_and_mp3_controls_survive() {
    let mut r = request();
    r.speed = Some(1.5);
    r.volume_scale = Some(2.0);
    r.pitch_bias = Some(0.0);
    r.replacements = Some(vec![TtsRequestText77d171beReplacementsItem {
        pattern: "Acme".into(),
        replacement: "ækmi".into(),
    }]);
    r.language = Some(TtsRequestTexte253c939Language::Fa(Default::default()));
    r.text_normalization = Some(TtsRequestText77d171beOutputMp3ConstantBitRate::True(
        Default::default(),
    ));
    r.output = Some(TtsRequestTextf2dcc77eOutput::Mp3(
        TtsRequestText77d171beOutputMp3 {
            format: Default::default(),
            sample_rate_hz: Some(TtsRequestText77d171beOutputFlacSampleRateHz::Number44100(
                Default::default(),
            )),
            bit_rate_bps: Some(TtsRequestText77d171beOutputMp3BitRateBps::Number256000(
                Default::default(),
            )),
            channel_count: Some(TtsRequestText77d171beOutputFlacChannelCount::Number2(
                Default::default(),
            )),
            constant_bit_rate: Some(TtsRequestText77d171beOutputMp3ConstantBitRate::False(
                Default::default(),
            )),
        },
    ));
    let r = TtsRequest::TextVoice9b47fc40(r);
    let _validate = validate_request(&r).unwrap();
    let c = settings::settings(r);
    assert_eq!(
        value(&encoded(&JsonValue::Object(c.wire))),
        value(
            r#"{"model":"speech-2.8-hd","language_boost":"Persian","voice_setting":{"voice_id":"existing-voice","speed":1.5,"vol":2,"pitch":0,"latex_read":false,"text_normalization":true},"audio_setting":{"format":"mp3","sample_rate":44100,"channel":2,"bitrate":256000,"force_cbr":false},"pronunciation_dict":{"tone":["Acme/ækmi"]}}"#
        )
    );
}


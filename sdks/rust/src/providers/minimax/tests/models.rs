#[test]
fn codecs_resolve_native_formats_without_guessing_pcm_encoding() {
    use super::super::format::IntoAudio;
    let formats = vec![
        TtsRequestText77d171beOutputMp3 {
            bit_rate_bps: None,
            channel_count: None,
            constant_bit_rate: None,
            format: Default::default(),
            sample_rate_hz: None,
        }
        .into_audio(),
        TtsRequestText77d171beOutputFlac {
            channel_count: None,
            format: Default::default(),
            sample_rate_hz: None,
        }
        .into_audio(),
        TtsRequestText77d171beOutputWav {
            channel_count: None,
            format: Default::default(),
            sample_rate_hz: None,
        }
        .into_audio(),
        TtsRequestTextf2dcc77eOutputMulaw {
            channel_count: None,
            format: Default::default(),
            sample_rate_hz: None,
        }
        .into_audio(),
        TtsRequestTextf2dcc77eOutputWav6dd8e06a {
            channel_count: None,
            format: Default::default(),
            sample_encoding: Default::default(),
            sample_rate_hz: None,
        }
        .into_audio(),
        TtsRequestTextf2dcc77eOutputOggOpus {
            channel_count: None,
            format: Default::default(),
            sample_rate_hz: None,
        }
        .into_audio(),
    ];
    for (audio, (format, rate)) in formats.into_iter().zip([
        ("mp3", 32000.0),
        ("flac", 32000.0),
        ("wav", 32000.0),
        ("pcmu_raw", 8000.0),
        ("pcmu_wav", 8000.0),
        ("opus", 24000.0),
    ]) {
        let (wire, native) = audio.wire(false);
        assert_eq!(native, format);
        assert_eq!(wire["sample_rate"], JsonValue::Number(rate));
        assert_eq!(wire["channel"], JsonValue::Number(1.0));
        if format == "mp3" {
            assert_eq!(wire["force_cbr"], JsonValue::Bool(false));
            assert_eq!(wire["bitrate"], JsonValue::Number(128000.0));
        }
    }
}

export interface LovoContracts {
  readonly synthesizePath: string;
  readonly jobPath: string;
  readonly speakersPath: string;
}

function record(value: unknown, name: string): Record<string, any> {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new TypeError(`LOVO ${name} must be an object`);
  }
  return value as Record<string, any>;
}

function operation(
  paths: Record<string, any>,
  path: string,
  method: "get" | "post",
  operationId: string,
): Record<string, any> {
  const value = record(record(paths[path], path)[method], `${method.toUpperCase()} ${path}`);
  if (value.operationId !== operationId) {
    throw new TypeError(`LOVO operation changed: ${method.toUpperCase()} ${path}`);
  }
  return value;
}

function schemaReference(value: unknown, expected: string, name: string): void {
  if (record(value, name).$ref !== `#/components/schemas/${expected}`) {
    throw new TypeError(`LOVO ${name} schema changed`);
  }
}

function responseSchema(operation: Record<string, any>, status: string, name: string): unknown {
  return record(record(record(record(operation.responses, `${name} responses`)[status], `${name} response`).content,
    `${name} response content`)["application/json"], `${name} JSON response`).schema;
}

function requireProperties(
  schemas: Record<string, any>,
  name: string,
  expected: readonly string[],
  required: readonly string[],
): void {
  const schema = record(schemas[name], name);
  const actual = Object.keys(record(schema.properties, `${name} properties`));
  if (JSON.stringify(actual) !== JSON.stringify(expected)
    || JSON.stringify(schema.required) !== JSON.stringify(required)) {
    throw new TypeError(`LOVO ${name} schema changed`);
  }
}

export function lovoContracts(value: unknown): LovoContracts {
  const openapi = record(value, "OpenAPI document");
  if (openapi.openapi !== "3.0.0" || record(openapi.info, "OpenAPI info").title !== "Genny API") {
    throw new TypeError("LOVO OpenAPI identity changed");
  }
  const paths = record(openapi.paths, "OpenAPI paths");
  const synthesizePath = "/api/v1/tts/sync";
  const jobPath = "/api/v1/tts/{jobId}";
  const speakersPath = "/api/v1/speakers";
  const synthesize = operation(paths, synthesizePath, "post", "sync-tts");
  const job = operation(paths, jobPath, "get", "async-retrieve-job");
  const speakers = operation(paths, speakersPath, "get", "retrieve-speakers");
  const request = record(record(record(synthesize.requestBody, "synthesize request body").content,
    "synthesize request content")["application/json"], "synthesize JSON request");
  schemaReference(request.schema, "TextToSpeechSyncRequest", "synthesize request");
  schemaReference(responseSchema(synthesize, "201", "synthesize"), "TextToSpeechSyncResponse", "synthesize response");
  schemaReference(responseSchema(job, "200", "job"), "TextToSpeechResponse", "job response");
  const speakerResponse = record(responseSchema(speakers, "200", "speakers"), "speakers response");
  if (!Array.isArray(speakerResponse.allOf) || speakerResponse.allOf.length !== 2) {
    throw new TypeError("LOVO speakers response schema changed");
  }

  const schemas = record(record(openapi.components, "OpenAPI components").schemas, "OpenAPI schemas");
  requireProperties(schemas, "TextToSpeechSyncRequest", ["text", "speaker", "speakerStyle", "speed"], ["text", "speaker"]);
  requireProperties(schemas, "TextToSpeechOutput", [
    "status", "text", "speaker", "speakerStyle", "speed", "pause", "emphasis", "urls",
    "pronunciations", "error",
  ], ["status", "text", "speaker", "speakerStyle", "speed", "pause", "emphasis", "pronunciations"]);
  requireProperties(schemas, "TextToSpeechSyncResponse", [
    "id", "type", "status", "progress", "team", "workspace", "project", "error", "createdAt",
    "estimatedTimeAt", "estimatedTimeMs", "data",
  ], ["id", "type", "status", "progress", "team", "createdAt", "data"]);
  requireProperties(schemas, "TextToSpeechResponse", [
    "id", "type", "status", "progress", "team", "workspace", "project", "error", "createdAt",
    "estimatedTimeAt", "estimatedTimeMs", "callbackUrls", "data",
  ], ["id", "type", "status", "progress", "team", "createdAt", "callbackUrls", "data"]);
  requireProperties(schemas, "GetSpeakersApiResponse", [
    "id", "displayName", "locale", "gender", "imageUrl", "ageRange", "speakerStyles",
  ], ["id", "displayName", "locale", "gender", "imageUrl"]);
  requireProperties(schemas, "PublicSpeakerStyleResType", [
    "displayName", "deprecated", "sampleTtsUrl", "id",
  ], ["displayName", "deprecated", "sampleTtsUrl", "id"]);
  return { synthesizePath, jobPath, speakersPath };
}

export function renderLovoClient(contract: LovoContracts, source: string): string {
  return `// Generated by codegen/generate-clients.ts from ${source}. Do not edit.
import type { Fetch } from "../../runtime/fetch.ts";

export interface SynthesizeRequest {
  readonly text: string;
  readonly speaker: string;
  readonly speakerStyle?: string;
  readonly speed?: number;
}

export interface JobError {
  readonly code: string;
  readonly message: string;
}

export interface SpeechOutput {
  readonly status: "pending" | "succeeded" | "failed";
  readonly text: string;
  readonly speaker: string;
  readonly speakerStyle: string;
  readonly speed: number;
  readonly urls?: readonly string[];
  readonly error?: JobError;
}

export interface SpeechJob {
  readonly id: string;
  readonly type: "tts" | "simple_tts" | "dubbing" | "localization" | "subtitles";
  readonly status: "in_progress" | "done";
  readonly progress: number;
  readonly team: string;
  readonly error?: JobError;
  readonly data: readonly SpeechOutput[];
}

export interface SpeakerStyle {
  readonly displayName: string;
  readonly deprecated: boolean;
  readonly sampleTtsUrl: string;
  readonly id: string;
}

export interface Speaker {
  readonly id: string;
  readonly displayName: string;
  readonly locale: string;
  readonly gender: "male" | "female" | "other";
  readonly imageUrl: string;
  readonly ageRange?: "child" | "children" | "young_adult" | "mature" | "mature_adult" | "old" | "other";
  readonly speakerStyles?: SpeakerStyle;
}

export interface SpeakerPage {
  readonly totalCount: number;
  readonly count: number;
  readonly data: readonly Speaker[];
  readonly page?: number;
  readonly limit?: number;
}

export interface ClientOptions {
  readonly apiKey: string;
  readonly baseUrl: string;
  readonly fetch: Fetch;
  readonly signal?: AbortSignal;
}

async function requestJson<ResponseBody>(
  path: string | URL,
  options: ClientOptions,
  init: RequestInit = {},
): Promise<ResponseBody> {
  const response = await options.fetch(path instanceof URL ? path : new URL(path, options.baseUrl), {
    ...init,
    headers: { "X-API-KEY": options.apiKey, ...init.headers },
    signal: options.signal,
  });
  if (!response.ok) {
    const detail = (await response.text()).trim();
    throw new TypeError(\`LOVO returned HTTP \${response.status}\${detail ? \`: \${detail}\` : ""}\`);
  }
  return response.json() as Promise<ResponseBody>;
}

export function createSpeech(input: SynthesizeRequest, options: ClientOptions): Promise<SpeechJob> {
  return requestJson<SpeechJob>(${JSON.stringify(contract.synthesizePath)}, options, {
    method: "POST",
    headers: { "content-type": "application/json; charset=utf-8" },
    body: JSON.stringify(input),
  });
}

export function getSpeech(jobId: string, options: ClientOptions): Promise<SpeechJob> {
  return requestJson<SpeechJob>(
    ${JSON.stringify(contract.jobPath)}.replace("{jobId}", encodeURIComponent(jobId)),
    options,
  );
}

export interface ListSpeakersRequest {
  readonly sort?: readonly string[];
  readonly page?: number;
  readonly limit?: number;
}

export function listSpeakers(input: ListSpeakersRequest, options: ClientOptions): Promise<SpeakerPage> {
  const url = new URL(${JSON.stringify(contract.speakersPath)}, options.baseUrl);
  for (const sort of input.sort ?? []) url.searchParams.append("sort", sort);
  if (input.page !== undefined) url.searchParams.set("page", String(input.page));
  if (input.limit !== undefined) url.searchParams.set("limit", String(input.limit));
  return requestJson<SpeakerPage>(url, options);
}
`;
}

export interface MicrosoftContracts {
  readonly synthesisPath: string;
  readonly resourceVoiceListPath: string;
  readonly outputFormats: readonly string[];
}

function record(value: unknown, name: string): Record<string, any> {
  if (!value || typeof value !== "object" || Array.isArray(value)) {
    throw new TypeError(`Microsoft ${name} must be an object`);
  }
  return value as Record<string, any>;
}

export function microsoftContracts(
  swaggerValue: unknown,
  rest: string,
  typeSpec: readonly string[],
  highDefinitionVoices: string,
  maiVoices: string,
): MicrosoftContracts {
  const swagger = record(swaggerValue, "management Swagger");
  const info = record(swagger.info, "management Swagger info");
  if (swagger.swagger !== "2.0" || info.title !== "Custom voice API" || info.version !== "2026-01-01") {
    throw new TypeError("Microsoft management Swagger identity changed");
  }
  const paths = record(swagger.paths, "management Swagger paths");
  if (paths["/cognitiveservices/v1"] !== undefined
    || record(record(paths["/models"], "models path").get, "models GET").operationId !== "Models_List"
    || record(record(paths["/basemodels"], "base models path").get, "base models GET").operationId !== "BaseModels_List"
    || record(record(paths["/endpoints"], "endpoints path").get, "endpoints GET").operationId !== "Endpoints_List") {
    throw new TypeError("Microsoft management and synthesis contracts are no longer separate");
  }
  if (typeSpec.length !== 4
    || !typeSpec[0]?.includes('import "./routes.tsp";')
    || !typeSpec[0]?.includes('import "./client.tsp";')
    || !typeSpec[1]?.includes('import "./models.tsp";')
    || !typeSpec[2]?.includes("model Model {")
    || !typeSpec[3]?.includes("@@clientName")) {
    throw new TypeError("Microsoft TypeSpec package changed");
  }

  const synthesisPath = /POST (\/cognitiveservices\/v1) HTTP\/1\.1/.exec(rest)?.[1];
  const resourceVoiceListPath = /[Uu]se the `(\/tts\/cognitiveservices\/voices\/list)` path/.exec(rest)?.[1];
  const streaming = /#### \[Streaming\]\(#tab\/streaming\)\n\n```\n([\s\S]*?)\n```/.exec(rest)?.[1];
  if (!synthesisPath || !resourceVoiceListPath || !streaming
    || !rest.includes("X-Microsoft-OutputFormat")
    || !rest.includes("Ocp-Apim-Subscription-Key")
    || !rest.includes("the body of the response contains an audio file")) {
    throw new TypeError("Microsoft synthesis REST documentation changed");
  }
  const outputFormats = streaming.split("\n").filter(Boolean);
  for (const format of [
    "audio-16khz-32kbitrate-mono-mp3",
    "audio-24khz-160kbitrate-mono-mp3",
    "audio-48khz-192kbitrate-mono-mp3",
    "ogg-48khz-16bit-mono-opus",
    "raw-8khz-16bit-mono-pcm",
    "raw-8khz-8bit-mono-mulaw",
  ]) {
    if (!outputFormats.includes(format)) throw new TypeError(`Microsoft output format disappeared: ${format}`);
  }
  if (!highDefinitionVoices.includes("en-US-Ava:DragonHDLatestNeural")
    || !highDefinitionVoices.includes(":DragonHDOmniLatestNeural")
    || !maiVoices.includes("MAI-Voice-2-Flash")
    || !maiVoices.includes("Use the voice name in the `name` attribute")) {
    throw new TypeError("Microsoft voice model documentation changed");
  }
  return { synthesisPath, resourceVoiceListPath, outputFormats };
}

export function renderMicrosoftClient(contract: MicrosoftContracts, sources: readonly string[]): string {
  return `// Generated by codegen/generate-clients.ts from ${sources.join(", ")}. Do not edit.
import type { Fetch } from "../../runtime/fetch.ts";

export const synthesisPath = ${JSON.stringify(contract.synthesisPath)};
export const resourceVoiceListPath = ${JSON.stringify(contract.resourceVoiceListPath)};

export interface ClientOptions {
  readonly url: string;
  readonly credential: { readonly kind: "apiKey" | "accessToken"; readonly value: string };
  readonly fetch: Fetch;
  readonly signal?: AbortSignal;
}

function authorization(credential: ClientOptions["credential"]): Record<string, string> {
  return credential.kind === "accessToken"
    ? { authorization: \`Bearer \${credential.value}\` }
    : { "Ocp-Apim-Subscription-Key": credential.value };
}

export function createSpeech(
  ssml: string,
  outputFormat: string,
  userAgent: string,
  options: ClientOptions,
): Promise<Response> {
  return options.fetch(options.url, {
    method: "POST",
    headers: {
      ...authorization(options.credential),
      "content-type": "application/ssml+xml",
      "X-Microsoft-OutputFormat": outputFormat,
      "User-Agent": userAgent,
    },
    body: ssml,
    signal: options.signal,
  });
}

export async function listVoices(options: ClientOptions): Promise<unknown> {
  const response = await options.fetch(options.url, {
    headers: authorization(options.credential),
    signal: options.signal,
  });
  if (!response.ok) {
    const detail = (await response.text()).trim();
    throw new TypeError(\`Microsoft Azure Speech returned HTTP \${response.status}\${detail ? \`: \${detail}\` : ""}\`);
  }
  return response.json() as Promise<unknown>;
}
`;
}

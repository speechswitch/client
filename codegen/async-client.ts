interface Schema {
  readonly type?: string;
  readonly enum?: readonly string[];
  readonly properties?: Readonly<Record<string, Schema>>;
  readonly required?: readonly string[];
  readonly items?: Schema;
}
interface Operation {
  readonly summary?: string;
  readonly parameters?: readonly { readonly name?: string; readonly in?: string; readonly required?: boolean }[];
  readonly requestBody?: { readonly content?: Readonly<Record<string, { readonly schema?: Schema }>> };
  readonly responses?: Readonly<Record<string, { readonly content?: Readonly<Record<string, { readonly schema?: Schema }>> }>>;
}
interface Api {
  readonly openapi?: string;
  readonly paths?: Readonly<Record<string, Readonly<Record<string, Operation>>>>;
}

function operation(api: Api, path: string, method: string): Operation {
  const value = api.paths?.[path]?.[method];
  if (!value) throw new TypeError(`Async contract lost ${method.toUpperCase()} ${path}`);
  return value;
}

export interface AsyncContract {
  readonly server: "https://api.async.com";
  readonly webSocketServer: "wss://api.async.com/text_to_speech/websocket/ws";
  readonly models: readonly ["async_pro_v1.0", "async_flash_v1.5", "async_flash_v1.0"];
  readonly languages: readonly ["en", "fr", "es", "de", "it", "pt", "ar", "ru", "ro", "ja", "he", "hy", "tr", "hi", "zh"];
}

export function asyncContract(value: unknown, webSocket: string, models: string): AsyncContract {
  const api = value as Api;
  if (api.openapi !== "3.1.0") throw new TypeError("Async OpenAPI version changed");
  const paths = [
    ["/text_to_speech", "post"],
    ["/text_to_speech/streaming", "post"],
    ["/text_to_speech/with_timestamps", "post"],
    ["/voices/clone", "post"],
    ["/voices", "post"],
    ["/voices/{id}", "get"],
    ["/voices/{id}", "put"],
    ["/voices/{id}", "delete"],
    ["/voices/batch", "post"],
    ["/voices/preview/{id}", "get"],
  ] as const;
  for (const [path, method] of paths) operation(api, path, method);
  const tts = operation(api, "/text_to_speech", "post");
  const body = tts.requestBody?.content?.["application/json"]?.schema;
  const wireModels = body?.properties?.model_id?.enum;
  const languages = body?.properties?.language?.enum;
  const headers = tts.parameters?.filter((parameter) => parameter.in === "header" && parameter.required).map(({ name }) => name);
  if (JSON.stringify(wireModels) !== JSON.stringify(["async_pro_v1.0", "async_flash_v1.5", "async_flash_v1.0"])
    || JSON.stringify(languages) !== JSON.stringify(["en", "fr", "es", "de", "it", "pt", "ar", "ru", "ro", "ja", "he", "hy", "tr", "hi", "zh"])
    || JSON.stringify(headers) !== JSON.stringify(["x-api-key", "version"])) {
    throw new TypeError("Async synthesis request contract changed");
  }
  if (!webSocket.includes("wss://api.async.com/text_to_speech/websocket/ws")
    || !webSocket.includes("`api_key`")
    || !webSocket.includes("`close_context`")
    || !webSocket.includes("`final`")
    || !webSocket.includes("`terminate`")) {
    throw new TypeError("Async WebSocket protocol changed");
  }
  if (!models.includes("`async_pro_v1.0`") || !models.includes("`async_flash_v1.5`") || !models.includes("`async_flash_v1.0`")) {
    throw new TypeError("Async model catalog changed");
  }
  return {
    server: "https://api.async.com",
    webSocketServer: "wss://api.async.com/text_to_speech/websocket/ws",
    models: wireModels as AsyncContract["models"],
    languages: languages as AsyncContract["languages"],
  };
}

export function renderAsyncClient(contract: AsyncContract, urls: readonly string[]): string {
  const models = contract.models.map((value) => JSON.stringify(value)).join(" | ");
  const languages = contract.languages.map((value) => JSON.stringify(value)).join(" | ");
  return `// Generated by codegen/generate-clients.ts from ${urls.join(", ")}. Do not edit.
import type { Fetch } from "../../runtime/fetch.ts";
export type Model = ${models};
export type Language = ${languages};
export type Gender = "Male" | "Female" | "Neutral" | "Unspecified";
export interface OutputFormat { readonly container: "raw" | "mp3" | "wav"; readonly encoding?: "pcm_f32le" | "pcm_s16le" | "pcm_mulaw"; readonly sample_rate: number; readonly bit_rate?: number }
export interface TtsInput { readonly model_id: Model; readonly transcript: string; readonly voice: { readonly mode: "id"; readonly id: string }; readonly output_format: OutputFormat; readonly language?: Language; readonly speed_control?: number; readonly stability?: number }
export interface TimestampResponse { readonly audio_base64: string; readonly alignment: { readonly words: readonly string[]; readonly word_start_times_milliseconds: readonly number[]; readonly word_end_times_milliseconds: readonly number[] } }
export interface Voice { readonly voice_id: string; readonly voice_type: "PREDEFINED" | "CUSTOM"; readonly name: string; readonly description: string; readonly created_at: string; readonly updated_at: string; readonly language: string; readonly gender: Gender; readonly accent: string; readonly style: string }
export interface VoiceList { readonly voices: readonly Voice[]; readonly next_cursor: string }
export interface VoiceFilters { readonly limit?: number; readonly model_id?: "async_flash_v1.0"; readonly language?: Language | "nl"; readonly accent?: string; readonly gender?: Gender; readonly style?: string; readonly my_voice?: boolean; readonly after?: string }
export interface VoiceUpdate { readonly name?: string; readonly gender?: Gender; readonly style?: string; readonly accent?: string }
export interface ClonedVoice { readonly id: string; readonly name: string; readonly description: string; readonly language: string }
export interface ClientOptions { readonly apiKey: string; readonly fetch: Fetch; readonly baseUrl: string; readonly signal?: AbortSignal }
export const defaultBaseUrl = ${JSON.stringify(contract.server)};
export const defaultWebSocketUrl = ${JSON.stringify(contract.webSocketServer)};
function request(path: string, method: string, body: BodyInit | undefined, contentType: string | undefined, options: ClientOptions): Promise<Response> { const headers: Record<string, string> = { "x-api-key": options.apiKey, version: "v1" }; if (contentType) headers["content-type"] = contentType; return options.fetch(new URL(path, options.baseUrl), { method, headers, body, signal: options.signal }); }
function json(path: string, method: string, body: unknown, options: ClientOptions): Promise<Response> { return request(path, method, body === undefined ? undefined : JSON.stringify(body), "application/json", options); }
export function synthesize(input: TtsInput, mode: "file" | "stream" | "timestamps", options: ClientOptions): Promise<Response> { const path = mode === "file" ? "/text_to_speech" : mode === "stream" ? "/text_to_speech/streaming" : "/text_to_speech/with_timestamps"; return json(path, "POST", input, options); }
export function listVoices(input: VoiceFilters, options: ClientOptions): Promise<Response> { return json("/voices", "POST", input, options); }
export function getVoice(voiceId: string, options: ClientOptions): Promise<Response> { return request(\`/voices/\${encodeURIComponent(voiceId)}\`, "GET", undefined, undefined, options); }
export function getVoices(voiceIds: readonly string[], options: ClientOptions): Promise<Response> { return json("/voices/batch", "POST", { voice_ids: voiceIds }, options); }
export function updateVoice(voiceId: string, input: VoiceUpdate, options: ClientOptions): Promise<Response> { return json(\`/voices/\${encodeURIComponent(voiceId)}\`, "PUT", input, options); }
export function deleteVoice(voiceId: string, options: ClientOptions): Promise<Response> { return request(\`/voices/\${encodeURIComponent(voiceId)}\`, "DELETE", undefined, undefined, options); }
export function previewVoice(voiceId: string, options: ClientOptions): Promise<Response> { return request(\`/voices/preview/\${encodeURIComponent(voiceId)}\`, "GET", undefined, undefined, options); }
export function cloneVoice(form: FormData, options: ClientOptions): Promise<Response> { return request("/voices/clone", "POST", form, undefined, options); }
`;
}
